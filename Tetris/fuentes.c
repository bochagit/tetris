  if (c == 'I') return font_I;
  if (c == 'N') return font_N;
  if (c == 'O') return font_O;
  if (c == 'P') return font_P;
  if (c == 'R') return font_R;
  if (c == 'S') return font_S;
  if (c == 'T') return font_T;
